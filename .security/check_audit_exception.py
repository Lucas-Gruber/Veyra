#!/usr/bin/env python3
"""Evaluate raw cargo-audit output using the recorded Alpha3-only owner decision."""
import argparse
from datetime import date, datetime, timedelta, timezone
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tomllib

SOURCE = 'd7506000f7b5b66ef8958339949079811e20ca0d'
SDK = 'b865d1db0025d9d12bea871a3a131c05aaeed205'
APP = '0.1.0-alpha.3'
ADVISORY = 'RUSTSEC-2023-0071'
RSA = '0.10.0-rc.19'
SDK_URL = 'https://github.com/bitwarden/sdk-internal'
SCOPE = ('.',)
# Explicit build/cache outputs and non-executable documentation only. Git ignore
# rules cannot hide source from this inventory. The evaluator hashes itself;
# its policy is intentionally not self-hashed.
EXCLUDED = ('node_modules/**', '.nuxt/**', '.output/**', '.data/**', '.pnpm-store/**',
            'coverage/**', 'playwright-report/**', 'test-results/**', 'dist', 'dist/**',
            '.flatpak-builder/**', 'artifacts/**', 'src-tauri/target/**',
            'src-tauri/gen/**', 'src-tauri/permissions/autogenerated/**', 'docs/**',
            '*.log', '**/*.log', '.security/rsa-alpha3-policy.json',
            '.security/check_audit_exception.py', 'AGENTS.md', 'README.md',
            '__pycache__/**', '**/__pycache__/**')

SETTINGS = {'target_arch': [], 'target_os': [], 'severity': None, 'ignore': [],
            'informational_warnings': ['unmaintained', 'unsound', 'notice']}


class ReviewRequired(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise ReviewRequired(message)


def pairs_unique(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, 'Duplicate JSON object key.')
        result[key] = value
    return result


def read_json(path):
    raw = Path(path).read_bytes()
    require(len(raw) <= 8 * 1024 * 1024, 'JSON report/policy exceeds the size limit.')
    def bad_constant(_):
        raise ReviewRequired('Non-finite JSON constant.')
    return json.loads(raw, object_pairs_hook=pairs_unique, parse_constant=bad_constant)


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def source_fingerprint(root):
    root = root.resolve()
    names = subprocess.run(['git', '-C', str(root), 'ls-files', '-co', '-z', '--',
                            *SCOPE, *(f':(exclude,glob){p}' for p in EXCLUDED)],
                           check=True, stdout=subprocess.PIPE).stdout.split(b'\0')
    inventory = {}
    for encoded in sorted(set(filter(None, names))):
        name = encoded.decode('utf-8')
        file = root / name
        require(not (file.name == '.env' or file.name.startswith('.env.'))
                or file.name.endswith('.example'), 'Local dotenv file requires review.')
        require(not file.is_symlink() and file.is_file(), 'Source must be a regular file.')
        require(file.resolve().is_relative_to(root), 'Source escapes repository root.')
        inventory[name] = hashlib.sha256(file.read_bytes()).hexdigest()
    require(inventory, 'Protected source inventory is empty.')
    return digest(inventory), inventory


def project_lock(root):
    return tomllib.loads((root / 'src-tauri/Cargo.lock').read_text())


def evaluate(root, report, status, stderr, policy, now=None):
    """Return a verdict or raise ReviewRequired. `now` exists only for unit tests."""
    now = now or datetime.now(timezone.utc)
    require(type(status) is int and status in (0, 1), 'Audit tool/network failure or unknown exit code.')
    require(stderr == b'', 'Audit emitted diagnostics; review raw stderr before continuing.')
    require(isinstance(report, dict) and set(report) == {
        'database', 'lockfile', 'settings', 'vulnerabilities', 'warnings'}, 'Unexpected audit schema.')
    require(report['settings'] == SETTINGS, 'Audit filtering, suppression or settings drift.')
    database = report['database']
    require(isinstance(database, dict)
            and type(database.get('advisory-count')) is int and database['advisory-count'] > 0
            and re.fullmatch('[0-9a-f]{40}', database.get('last-commit', '')) is not None
            and isinstance(database.get('last-updated'), str), 'Invalid advisory database metadata.')
    updated = datetime.fromisoformat(database['last-updated'])
    require(updated.tzinfo is not None and updated <= now + timedelta(minutes=5),
            'Invalid/future advisory database timestamp.')
    require(isinstance(report['lockfile'], dict), 'Invalid lockfile report.')
    count = report['lockfile'].get('dependency-count')
    require(type(count) is int and count == len(project_lock(root)['package']),
            'Audit does not cover the current complete Cargo.lock.')
    warnings = report['warnings']
    require(isinstance(warnings, dict), 'Invalid warning report.')
    warning_hashes = []
    for group, findings in warnings.items():
        require(group in SETTINGS['informational_warnings'] and isinstance(findings, list),
                'Unexpected warning group.')
        for finding in findings:
            require(isinstance(finding, dict)
                    and finding.get('advisory', {}).get('informational') == group,
                    'Invalid informational audit warning.')
            warning_hashes.append(digest(finding))
    vulnerabilities = report['vulnerabilities']
    require(isinstance(vulnerabilities, dict) and set(vulnerabilities) == {'found', 'count', 'list'},
            'Invalid vulnerability report.')
    findings = vulnerabilities['list']
    require(isinstance(findings, list) and type(vulnerabilities['count']) is int
            and vulnerabilities['count'] == len(findings)
            and type(vulnerabilities['found']) is bool
            and vulnerabilities['found'] == bool(findings), 'Inconsistent vulnerability counts.')
    if not findings:
        require(status == 0, 'Audit failed without a vulnerability result.')
        return 'Clean unsuppressed audit; no RSA exception used.'
    require(status == 1 and len(findings) == 1, 'Only one exact reviewed RSA finding may be considered.')
    require(all(value in policy['known_warning_sha256'] for value in warning_hashes),
            'New or changed audit warning needs review before using the RSA exception.')
    finding = findings[0]
    require(isinstance(finding, dict)
            and finding.get('advisory', {}).get('id') == ADVISORY
            and finding.get('package', {}).get('name') == 'rsa'
            and finding.get('package', {}).get('version') == RSA,
            'Finding is outside the recorded RSA exception.')
    require(digest(finding) == policy['finding_sha256'], 'RSA advisory/package details changed.')
    require(policy.get('format') == 2 and policy.get('reviewed_source_commit') == SOURCE
            and policy.get('app_version') == APP
            and policy.get('sdk_revision') == SDK and policy.get('advisory') == ADVISORY
            and policy.get('rsa_version') == RSA, 'Policy identity or scope drift.')
    approval = policy['approval']
    require(approval.get('approved') is True and all(
        isinstance(approval.get(k), str) and approval[k].strip()
        for k in ('by', 'reference', 'on')), 'No explicit owner approval is recorded.')
    approved = date.fromisoformat(approval['on'])
    require(approved <= now.date(), 'Owner approval date is in the future.')
    require(hashlib.sha256(Path(__file__).read_bytes()).hexdigest() == policy['guard_sha256'],
            'Evaluator implementation changed; new review is required.')
    manifest = tomllib.loads((root / 'src-tauri/Cargo.toml').read_text())
    package = read_json(root / 'package.json')
    tauri = read_json(root / 'src-tauri/tauri.conf.json')
    require(package['version'] == manifest['package']['version'] == tauri['version'] == APP,
            'Exception applies only to the reviewed Alpha3 application.')
    for name in ('bitwarden-core', 'bitwarden-crypto', 'bitwarden-vault', 'bitwarden-api-api'):
        dependency = manifest['dependencies'][name]
        require(dependency.get('git') == SDK_URL and dependency.get('rev') == SDK,
                'SDK release pin changed.')
    lock = project_lock(root)
    rsa = [p for p in lock['package'] if p['name'] == 'rsa']
    require(len(rsa) == 1 and rsa[0]['version'] == RSA
            and rsa[0].get('checksum') == finding['package'].get('checksum')
            and rsa[0].get('source') == finding['package'].get('source'), 'Locked RSA dependency drift.')
    sdk = [p for p in lock['package'] if SDK_URL in p.get('source', '')]
    require(len(sdk) == 24 and all(p['version'] == '4.0.0'
            and p['source'] == f'git+{SDK_URL}?rev={SDK}#{SDK}' for p in sdk), 'SDK lock graph changed.')
    fingerprint, inventory = source_fingerprint(root)
    require(digest(policy['protected_source_sha256']) == policy['source_fingerprint_sha256'],
            'Recorded source inventory is inconsistent.')
    require(fingerprint == policy['source_fingerprint_sha256']
            and inventory == policy['protected_source_sha256'], 'Protected source/CI fingerprint changed.')
    return 'Exact owner-approved Alpha3 RSA exception used; the raw finding remains unresolved.'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, required=True)
    parser.add_argument('--policy', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    parser.add_argument('--stderr', type=Path, required=True)
    parser.add_argument('--audit-exit', type=int, required=True)
    args = parser.parse_args()
    try:
        verdict = evaluate(args.repo, read_json(args.report), args.audit_exit,
                           args.stderr.read_bytes(), read_json(args.policy))
    except (ReviewRequired, OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError) as error:
        print(f'REVIEW REQUIRED: {error}', file=sys.stderr)
        return 1
    print(verdict)
    if verdict.startswith('Exact owner-approved'):
        print('::warning title=Alpha3 RSA risk exception::RUSTSEC-2023-0071 remains unresolved; the recorded owner exception applies only to this unchanged Alpha3 source.')
    return 0


if __name__ == '__main__':
    sys.exit(main())

import { expect, test, type Page } from '@playwright/test'
import { installConnectedVault } from './fixtures/connected-vault'

const rows = (page: Page) => page.locator('.item-row')
async function chooseVault(page: Page, name: string) {
  await page.getByRole('button', { name: 'Choose vault', exact: true }).click()
  await page.getByRole('menuitemradio', { name, exact: true }).click()
}

test.beforeEach(async ({ page }) => {
  await installConnectedVault(page)
  await page.goto('/')
  await expect(rows(page)).toHaveCount(4)
})

test('organizations and collections show their complete accessible scope, including empty organizations', async ({ page }) => {
  await chooseVault(page, 'Your vault')
  await expect(rows(page)).toHaveCount(1)
  await expect(rows(page)).toContainText('Personal fixture login')
  await chooseVault(page, 'Lantern Guild')
  await expect(rows(page)).toHaveCount(2)
  await expect(rows(page)).toContainText(['Finance fixture login', 'Platform fixture login'])
  await page.getByRole('button', { name: 'Collections', exact: true }).click()
  const collections = page.locator('.collection-filters')
  await expect(collections.getByRole('button', { name: 'Platform team', exact: true })).toBeVisible()
  await expect(collections.getByRole('button', { name: 'Operations', exact: true })).toHaveCount(0)
  await collections.getByRole('button', { name: 'Platform team', exact: true }).click()
  await expect(rows(page)).toHaveCount(1)
  await expect(rows(page)).toContainText('Platform fixture login')
  await collections.getByRole('button', { name: 'Finance team', exact: true }).click()
  await expect(rows(page)).toHaveCount(1)
  await expect(rows(page)).toContainText('Finance fixture login')
  await expect(page.getByRole('button', { name: 'Edit item', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Add to favorites', exact: true })).toBeDisabled()
  await chooseVault(page, 'River Cooperative')
  await expect(rows(page)).toHaveCount(1)
  await expect(rows(page)).toContainText('River fixture note')
  await chooseVault(page, 'Empty group')
  await expect(rows(page)).toHaveCount(0)
  await chooseVault(page, 'All vaults')
  await expect(rows(page)).toHaveCount(4)
  await page.keyboard.press('Control+l')
  await expect(rows(page)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Choose vault', exact: true })).toBeDisabled()
  await expect(page.getByText('Lantern Guild', { exact: true })).toHaveCount(0)
})

test('connected write UI creates, edits, favorites, trashes and restores an organization item through IPC', async ({ page }) => {
  await chooseVault(page, 'Lantern Guild')
  await page.getByRole('button', { name: 'New item', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'New item', exact: true })
  await editor.getByLabel('Name', { exact: true }).fill('Created synthetic login')
  await expect(editor.getByRole('combobox', { name: 'Vault', exact: true })).toHaveValue('org-lantern')
  await expect(editor.getByRole('button', { name: 'Save item', exact: true })).toBeDisabled()
  await expect(editor.getByRole('checkbox', { name: 'Finance team', exact: true })).toHaveCount(0)
  await expect(editor.getByRole('checkbox', { name: 'Restricted team', exact: true })).toHaveCount(0)
  await editor.getByRole('checkbox', { name: 'Platform team', exact: true }).check()
  await editor.getByLabel('Username', { exact: true }).fill('created-synthetic@example.test')
  await editor.getByLabel('Password', { exact: true }).fill('created-synthetic-password')
  await editor.getByLabel('Website · first URI', { exact: true }).fill('https://created.example.test/')
  await editor.getByLabel('Notes', { exact: true }).fill('Created synthetic secret note')
  await editor.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(editor).toHaveCount(0)
  await chooseVault(page, 'Lantern Guild')
  await expect(rows(page)).toHaveCount(3)
  await page.getByRole('button', { name: /Created synthetic login/ }).click()
  await page.getByRole('button', { name: 'Edit item', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Edit item', exact: true })
  await expect(edit.getByLabel('Password', { exact: true })).toHaveValue('created-synthetic-password')
  await expect(edit.getByRole('combobox', { name: 'Vault', exact: true })).toBeDisabled()
  await edit.getByLabel('Name', { exact: true }).fill('Renamed synthetic login')
  await edit.getByLabel('Password', { exact: true }).fill('updated-synthetic-password')
  await edit.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(edit).toHaveCount(0)
  await chooseVault(page, 'Lantern Guild')
  await page.getByRole('button', { name: /Renamed synthetic login/ }).click()
  await expect(page.getByRole('heading', { name: 'Renamed synthetic login', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add to favorites', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remove from favorites', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Move to trash', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm move to trash', exact: true }).click()
  await expect(rows(page)).toHaveCount(2)
  await page.getByRole('button', { name: 'Trash', exact: true }).click()
  await page.getByRole('button', { name: /Renamed synthetic login/ }).click()
  await page.getByRole('button', { name: 'Restore item', exact: true }).click()
  await expect(page.getByRole('button', { name: /Renamed synthetic login/ })).toHaveCount(0)
  await page.getByRole('button', { name: /^All items/ }).click()
  await expect(rows(page)).toHaveCount(3)
  await expect(rows(page).filter({ hasText: 'Renamed synthetic login' })).toBeVisible()
  const writes = await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => ['save_item', 'change_item'].includes(call.command)))
  expect(writes).toMatchObject([
    { command: 'save_item', args: { expectedGeneration: 1, draft: { id: null, name: 'Created synthetic login', organizationId: 'org-lantern', collectionIds: ['coll-platform'] } } },
    { command: 'save_item', args: { expectedGeneration: 1, draft: { id: 'created-fixture-1', name: 'Renamed synthetic login', password: 'updated-synthetic-password' } } },
    { command: 'change_item', args: { expectedGeneration: 1, request: { id: 'created-fixture-1', action: 'favorite', favorite: true } } },
    { command: 'change_item', args: { expectedGeneration: 1, request: { id: 'created-fixture-1', action: 'trash' } } },
    { command: 'change_item', args: { expectedGeneration: 1, request: { id: 'created-fixture-1', action: 'restore' } } },
  ])
})

test('save failures retain the editor for correction and never persist draft secrets', async ({ page }) => {
  await page.getByRole('button', { name: 'New item', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'New item', exact: true })
  await editor.getByLabel('Name', { exact: true }).fill('Unsaved synthetic name')
  await editor.getByLabel('Password', { exact: true }).fill('unsaved-synthetic-password')
  await editor.getByLabel('Notes', { exact: true }).fill('Unsaved synthetic secret note')
  await page.evaluate(() => { window.__VEYRA_UI_FIXTURE__.failNextSave = true })
  await editor.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(editor.getByRole('alert')).toContainText('Synthetic conflict')
  await expect(editor.getByLabel('Name', { exact: true })).toHaveValue('Unsaved synthetic name')
  await expect(editor.getByLabel('Password', { exact: true })).toHaveValue('unsaved-synthetic-password')
  await expect(editor.getByRole('button', { name: 'Save item', exact: true })).toBeEnabled()
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }))
  expect(storage).not.toMatch(/synthetic|example\.test|Lantern|Platform/)
  await editor.getByRole('button', { name: 'Close editor', exact: true }).click()
  await page.getByRole('button', { name: 'New item', exact: true }).click()
  await expect(editor.getByLabel('Name', { exact: true })).toHaveValue('')
  await expect(editor.getByLabel('Password', { exact: true })).toHaveValue('')
  await expect(editor.getByLabel('Notes', { exact: true })).toHaveValue('')
  await page.keyboard.press('Control+l')
  await expect(editor).toHaveCount(0)
  await expect(rows(page)).toHaveCount(0)
  await expect(page.getByLabel('Master password', { exact: true })).toHaveValue('')
})

test('locking while an editor response is pending cannot reopen it or restore its secrets', async ({ page }) => {
  await page.getByRole('button', { name: /Personal fixture login/ }).click()
  await page.evaluate(() => { window.__VEYRA_UI_FIXTURE__.delayNextEditor = true })
  await page.getByRole('button', { name: 'Edit item', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Edit item', exact: true })
  await expect(editor.getByRole('status')).toHaveText('Loading editor…')
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.pendingEditor)).toBe(true)
  await page.keyboard.press('Control+l')
  await expect(editor).toHaveCount(0)
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.releaseEditor())
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.pendingEditor)).toBe(false)
  await expect(editor).toHaveCount(0)
  await expect(rows(page)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Connect & unlock' })).toBeVisible()
  await expect(page.locator('body')).not.toContainText('Synthetic editor note')
  const writes = await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'save_item'))
  expect(writes).toEqual([])
})

test('explicit contents conceal on blur, timeout and lock, including a late IPC response', async ({ page }) => {
  await page.clock.install()
  await page.getByRole('button', { name: /Personal fixture login/ }).click()
  const notes = page.locator('.revealed-notes')
  await expect(notes).toHaveCount(0)
  await page.getByRole('button', { name: 'Show contents', exact: true }).click()
  await expect(notes).toHaveText('Synthetic editor note')
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await expect(notes).toHaveCount(0)
  await page.getByRole('button', { name: 'Show contents', exact: true }).click()
  await expect(notes).toBeVisible()
  await page.clock.fastForward(60_001)
  await expect(notes).toHaveCount(0)
  await page.evaluate(() => { window.__VEYRA_UI_FIXTURE__.delayNextEditor = true })
  await page.getByRole('button', { name: 'Show contents', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.pendingEditor)).toBe(true)
  await page.keyboard.press('Control+l')
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.releaseEditor())
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.pendingEditor)).toBe(false)
  await expect(notes).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Show contents', exact: true })).toHaveCount(0)
  await expect(page.locator('body')).not.toContainText('Synthetic editor note')
})

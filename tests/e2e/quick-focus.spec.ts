import { expect, test } from '@playwright/test'
import { installConnectedVault } from './fixtures/connected-vault'

test('Quick Access owns keyboard focus and dismisses on outside pointer down', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Explore demo vault' }).click()
  const mainSearch = page.getByRole('textbox', { name: 'Search your vault' })
  await mainSearch.focus()
  await page.keyboard.press('Control+Alt+Space')
  const dialog = page.getByRole('dialog', { name: 'Quick Access', exact: true })
  const search = dialog.getByRole('combobox')
  await expect(search).toBeFocused()
  await expect(page.locator('.app-frame')).toHaveAttribute('inert', '')
  await expect(page.locator('.app-statusbar')).toHaveAttribute('inert', '')
  await mainSearch.evaluate(element => element.focus())
  await expect(search).toBeFocused()
  await search.fill('proton')
  await page.mouse.move(8, 8)
  await page.mouse.down()
  await expect(dialog).toHaveCount(0)
  await page.mouse.up()
  await expect(mainSearch).toBeFocused()
  await expect(page.locator('.app-frame')).not.toHaveAttribute('inert')
  await page.keyboard.press('Control+Alt+Space')
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('proton')
})

test('browser window blur dismisses Quick Access and keeps its search for reopening', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Explore demo vault' }).click()
  await page.keyboard.press('Control+Alt+Space')
  const dialog = page.getByRole('dialog', { name: 'Quick Access', exact: true })
  await dialog.getByRole('combobox').fill('proton')
  // Headless tabs emulate focus independently. Deliver the DOM blur contract;
  // this does not establish native compositor focus behavior.
  await page.evaluate(() => window.dispatchEvent(new FocusEvent('blur')))
  await expect(dialog).toHaveCount(0)
  await page.keyboard.press('Control+Alt+Space')
  await expect(dialog.getByRole('combobox')).toBeFocused()
  await expect(dialog.getByRole('combobox')).toHaveValue('proton')
})

test('standalone browser Quick Access closes on window blur', async ({ page }) => {
  await page.goto('/?window=quick')
  const dialog = page.getByRole('dialog', { name: 'Quick Access', exact: true })
  await expect(dialog.getByRole('button', { name: 'Explore demo vault' })).toBeFocused()
  await page.evaluate(() => window.dispatchEvent(new FocusEvent('blur')))
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Choose vault', exact: true })).toBeVisible()
})

test('native activation focuses the restored search or sign-in form', async ({ page }) => {
  await installConnectedVault(page)
  await page.goto('/?window=quick')
  const dialog = page.getByRole('dialog', { name: 'Quick Access', exact: true })
  const search = dialog.getByRole('combobox')
  await expect(search).toBeFocused()
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.some(call => call.command === 'plugin:event|listen' && call.args?.event === 'quick-access:blur'))).toBe(true)
  await search.fill('Personal')
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.emitQuickBlur())
  const openMain = dialog.getByRole('button', { name: 'Open Veyra', exact: true })
  await openMain.focus()
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.emitQuickFocus())
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('Personal')
  await page.keyboard.press('Control+l')
  const server = dialog.getByLabel('Server address', { exact: true })
  await expect(server).toBeFocused()
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.emitQuickBlur())
  await openMain.focus()
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.emitQuickFocus())
  await expect(server).toBeFocused()
})

test('typing immediately reaches search on first open and WebView reactivation', async ({ page }) => {
  await installConnectedVault(page)
  await page.goto('/?window=quick')
  const dialog = page.getByRole('dialog', { name: 'Quick Access', exact: true })
  const search = dialog.getByRole('combobox')
  await expect(search).toBeFocused()
  // Type without locator.fill(), which would focus the field itself and mask
  // a missing initial input focus.
  await page.keyboard.type('Personal')
  await expect(search).toHaveValue('Personal')
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.some(call => call.command === 'plugin:event|listen' && call.args?.event === 'quick-access:blur'))).toBe(true)
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.emitQuickBlur())
  await dialog.getByRole('button', { name: 'Open Veyra', exact: true }).focus()
  // Exercise actual DOM focus delivery independently of the native IPC focus
  // notification, which may precede listener registration in a new WebView.
  await page.evaluate(() => window.dispatchEvent(new FocusEvent('focus')))
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('Personal')
  await page.keyboard.press('End')
  await page.keyboard.type(' fixture')
  await expect(search).toHaveValue('Personal fixture')
  // A later native notification must not overwrite typing or restore twice.
  await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.emitQuickFocus())
  await expect(search).toHaveValue('Personal fixture')
})

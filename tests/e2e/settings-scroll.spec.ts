import { expect, test } from '@playwright/test'

for (const viewport of [{ width: 1100, height: 540 }, { width: 800, height: 650 }, { width: 640, height: 540 }, { width: 390, height: 520 }, { width: 320, height: 400 }, { width: 1100, height: 360 }]) {
  test(`settings contain keyboard and wheel scrolling at ${viewport.width}×${viewport.height} with large text`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.addInitScript(() => localStorage.setItem('veyra:preferences', JSON.stringify({ textSize: 18 })))
    await page.goto('/')
    await expect(page.locator('html')).toHaveCSS('font-size', '18px')
    const documentOverflow = await page.locator('html').evaluate(element => element.style.overflow)
    await page.keyboard.press('Control+,')
    const dialog = page.getByRole('dialog', { name: 'Settings', exact: true })
    const body = dialog.getByRole('region', { name: 'Appearance settings' })
    const sidebar = dialog.locator('.settings-sidebar')
    await expect(dialog).toBeVisible()
    await expect(page.locator('.app-frame')).toHaveJSProperty('inert', true)
    await expect(page.locator('.app-statusbar')).toHaveJSProperty('inert', true)
    await expect(page.locator('.app-frame .sidebar')).toHaveCSS('overflow-y', 'hidden')
    await expect(page.locator('html')).toHaveCSS('overflow', 'hidden')
    const bounds = await dialog.boundingBox()
    expect(bounds).not.toBeNull()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(viewport.width)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height)
    expect(await sidebar.evaluate(element => element.scrollHeight <= element.clientHeight + 1)).toBe(true)
    expect(await sidebar.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    expect(await body.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await expect(body).toHaveCSS('overflow-y', 'auto')
    const before = await sidebar.boundingBox()
    const backgroundScroll = await page.evaluate(() => ({ document: document.scrollingElement?.scrollTop, sidebar: document.querySelector('.app-frame .sidebar')?.scrollTop }))
    await body.focus()
    await page.keyboard.press('End')
    await expect.poll(() => body.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
    await expect(body.getByText('Quietly violet.', { exact: false })).toBeInViewport()
    expect(await sidebar.boundingBox()).toEqual(before)
    await expect(dialog.getByRole('button', { name: 'Close settings', exact: true })).toBeInViewport()
    await expect(dialog.getByRole('button', { name: 'Security', exact: true })).toBeInViewport()
    expect(await dialog.evaluate(element => element.scrollTop)).toBe(0)
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await body.hover()
    await page.mouse.wheel(0, 800)
    await page.mouse.move(4, 4)
    await page.mouse.wheel(0, 800)
    expect(await page.evaluate(() => ({ document: document.scrollingElement?.scrollTop, sidebar: document.querySelector('.app-frame .sidebar')?.scrollTop }))).toEqual(backgroundScroll)
    await dialog.getByRole('button', { name: 'Quick Access', exact: true }).click()
    const quick = dialog.getByRole('region', { name: 'Quick Access settings' })
    await expect(quick).toHaveJSProperty('scrollTop', 0)
    expect(await quick.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await quick.hover()
    await page.mouse.wheel(0, 600)
    await expect.poll(() => quick.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
    await quick.focus()
    await page.keyboard.press('End')
    await expect(quick.getByText('Available with a connected native Linux vault.', { exact: true })).toBeInViewport()
    expect(await sidebar.boundingBox()).toEqual(before)
    await dialog.getByRole('button', { name: 'Security', exact: true }).click()
    const security = dialog.getByRole('region', { name: 'Security settings' })
    await expect(security).toHaveJSProperty('scrollTop', 0)
    expect(await security.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await dialog.getByRole('button', { name: 'About', exact: true }).click()
    const about = dialog.getByRole('region', { name: 'About settings' })
    await expect(about).toHaveJSProperty('scrollTop', 0)
    expect(await about.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await dialog.getByRole('button', { name: 'Close settings', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('.app-frame')).toHaveJSProperty('inert', false)
    await expect(page.locator('.app-frame .sidebar')).toHaveCSS('overflow-y', 'auto')
    expect(await page.locator('html').evaluate(element => element.style.overflow)).toBe(documentOverflow)
  })
}

test('settings restore focus to their opener after closing', async ({ page }) => {
  await page.goto('/')
  const opener = page.getByRole('button', { name: 'Settings', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Settings', exact: true })
  await expect(dialog.getByRole('button', { name: 'Close settings', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
})

import { expect, test } from '@playwright/test'
import { installConnectedVault } from './fixtures/connected-vault'

test.beforeEach(async ({ page }) => {
  await installConnectedVault(page, { folders: [{ id: 'mail', name: 'Work/Accounts' }, { id: 'empty', name: 'Empty' }], assignments: {} })
  await page.goto('/')
  await expect(page.locator('.item-row')).toHaveCount(4)
})

test('context menu is keyboard accessible, fits the viewport and closes outside', async ({ page }) => {
  const personal = page.locator('.item-row').filter({ hasText: 'Personal fixture login' })
  await personal.click({ button: 'right' })
  const menu = page.getByRole('menu', { name: 'Item actions', exact: true })
  await expect(menu.getByRole('menuitem', { name: 'Show item', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitem', { name: 'Open website', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await personal.focus()
  await personal.press('Shift+F10')
  await expect(menu).toBeVisible()
  const bounds = await menu.boundingBox(), viewport = page.viewportSize()!
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(viewport.width)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height)
  await page.getByRole('heading', { name: 'All items', exact: false }).click()
  await expect(menu).toHaveCount(0)
})

test('shift selection assigns a folder to the selected range and clears hidden selections', async ({ page }) => {
  const personal = page.locator('.item-row').filter({ hasText: 'Personal fixture login' })
  const platform = page.locator('.item-row').filter({ hasText: 'Platform fixture login' })
  await personal.click()
  await platform.click({ modifiers: ['Shift'] })
  await expect(page.getByRole('toolbar', { name: 'Selected items' })).toContainText('2 selected')
  await page.getByRole('button', { name: 'Assign folder', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Assign folder', exact: true })
  await dialog.getByRole('combobox', { name: 'Folder', exact: true }).selectOption('mail')
  await dialog.getByRole('button', { name: 'Apply to 2 items', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('2 of 2 completed.')
  const calls = await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'manage_items'))
  expect(calls).toMatchObject([{ args: { expectedGeneration: 1, request: { items: [{ id: 'personal-login' }, { id: 'platform-login' }], operation: { type: 'assign_folder', folderId: 'mail' } } } }])
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('treeitem').filter({ hasText: /^Accounts2$/ }).click()
  await expect(page.locator('.item-row')).toHaveCount(2)
  await page.getByRole('textbox', { name: 'Search your vault' }).fill('Personal')
  await expect(page.locator('.item-row')).toHaveCount(1)
  await expect(page.getByRole('toolbar', { name: 'Selected items' })).toHaveCount(0)
})

test('duplicate, collection assignment and vault move send concrete destinations', async ({ page }) => {
  const personal = page.locator('.item-row').filter({ hasText: 'Personal fixture login' })
  await personal.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Duplicate…', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Duplicate items', exact: true })
  await dialog.getByLabel('Destination vault').selectOption('org-lantern')
  await expect(dialog.getByRole('button', { name: 'Apply to 1 item' })).toBeDisabled()
  await dialog.getByRole('checkbox', { name: 'Platform team', exact: true }).check()
  await expect(dialog.getByRole('checkbox', { name: 'Finance team' })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Apply to 1 item' }).click()
  await expect(dialog.getByRole('status')).toHaveText('1 of 1 completed.')
  await dialog.getByRole('button', { name: 'Done' }).click()
  const copied = page.locator('.item-row').filter({ hasText: 'Personal fixture login (copy)' })
  await expect(copied).toBeVisible()
  await copied.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Assign collections…' }).click()
  dialog = page.getByRole('dialog', { name: 'Assign collections' })
  await expect(dialog.getByRole('checkbox', { name: 'Platform team' })).toBeChecked()
  await dialog.getByRole('button', { name: 'Apply to 1 item' }).click()
  await dialog.getByRole('button', { name: 'Done' }).click()
  await copied.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Move to another vault…' }).click()
  dialog = page.getByRole('dialog', { name: 'Move to another vault' })
  await dialog.getByLabel('Destination vault').selectOption('')
  await dialog.getByRole('button', { name: 'Apply to 1 item' }).click()
  await dialog.getByRole('button', { name: 'Done' }).click()
  const operations = await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'manage_items').map(call => (call.args?.request as { operation: unknown }).operation))
  expect(operations).toEqual([
    { type: 'copy', organizationId: 'org-lantern', collectionIds: ['coll-platform'], folderId: null },
    { type: 'assign_collections', collectionIds: ['coll-platform'] },
    { type: 'move', organizationId: null, collectionIds: [], folderId: null },
  ])
})

test('uncertain batch results are explicit, stop further writes and disappear on lock', async ({ page }) => {
  await page.locator('.item-row').filter({ hasText: 'Personal fixture login' }).click()
  await page.locator('.item-row').filter({ hasText: 'Platform fixture login' }).click({ modifiers: ['Shift'] })
  await page.evaluate(() => { window.__VEYRA_UI_FIXTURE__.uncertainBatchItem = 'personal-login' })
  await page.getByRole('button', { name: 'Assign folder', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Assign folder' })
  await dialog.getByRole('combobox', { name: 'Folder', exact: true }).selectOption('mail')
  await dialog.getByRole('button', { name: 'Apply to 2 items' }).click()
  await expect(dialog).toContainText('uncertain')
  await expect(dialog).toContainText('not attempted')
  await expect(dialog.getByRole('alert')).toContainText('Synchronize')
  await page.keyboard.press('Control+l')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(page.locator('.item-row')).toHaveCount(0)
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage }))).not.toMatch(/synthetic|fixture|Lantern|Platform/)
})

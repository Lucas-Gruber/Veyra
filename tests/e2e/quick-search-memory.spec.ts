import { expect, test } from '@playwright/test'
import { installConnectedVault } from './fixtures/connected-vault'

test('reopening the overlay restores its search for 30 seconds after dismissal', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Explore demo vault' }).click()
  await page.keyboard.press('Control+Alt+Space')
  const dialog = page.getByRole('dialog', { name: 'Quick Access', exact: true })
  const search = dialog.getByRole('combobox', { name: 'Search vault' })
  await search.fill('proton')
  await expect(dialog.getByRole('option')).toHaveCount(1)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.clock.fastForward(20_000)
  await page.keyboard.press('Control+Alt+Space')
  await expect(search).toHaveValue('proton')
  await expect(dialog.getByRole('option')).toContainText('Proton Mail')
  // An open search remains usable; the expiry applies while dismissed.
  await page.clock.fastForward(31_000)
  await expect(search).toHaveValue('proton')
  await page.locator('.quick-backdrop').click({ position: { x: 8, y: 8 } })
  await expect(dialog).toHaveCount(0)
  await page.clock.fastForward(31_000)
  await page.keyboard.press('Control+Alt+Space')
  await expect(search).toHaveValue('')
  await expect(dialog.getByRole('option')).toHaveCount(8)
  expect(await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }))).not.toContain('proton')
})


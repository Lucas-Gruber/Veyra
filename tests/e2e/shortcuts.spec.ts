import { expect, test } from '@playwright/test'
import { installConnectedVault } from './fixtures/connected-vault'

test('Quick Access uses exact clipboard defaults while preserving selected search text', async ({ page }) => {
  await installConnectedVault(page)
  await page.goto('/?window=quick')
  const search = page.getByRole('combobox', { name: 'Search vault' })
  await search.fill('Personal')
  await expect(page.getByRole('option')).toHaveCount(1)
  await search.press('Control+a')
  await page.keyboard.press('Control+c')
  expect(await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'copy_field'))).toEqual([])
  await search.press('ArrowRight')
  await page.keyboard.press('Control+c')
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'copy_field').length)).toBe(1)
  await search.fill('Personal')
  await expect(page.getByRole('option')).toHaveCount(1)
  await page.keyboard.press('Control+Shift+c')
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'copy_field').length)).toBe(2)
  await search.fill('Personal')
  await expect(page.getByRole('option')).toHaveCount(1)
  await page.keyboard.press('Control+Alt+c')
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'copy_field').length)).toBe(3)
  const copies = await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => call.command === 'copy_field'))
  expect(copies.map(call => call.args)).toEqual([
    { itemId: 'personal-login', field: 'username' }, { itemId: 'personal-login', field: 'password' }, { itemId: 'personal-login', field: 'totp' },
  ])
})

test('shortcut recording persists, rejects collisions and takes effect after reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Settings', exact: true })
  await settings.getByRole('button', { name: 'Quick Access', exact: true }).click()
  const recorder = settings.getByRole('button', { name: 'Change shortcut: Open Quick Access', exact: true })
  await recorder.click()
  await page.keyboard.press('Control+k')
  await expect(settings.getByRole('alert')).toContainText('already assigned')
  await page.keyboard.press('Control+Alt+q')
  await expect(recorder).toHaveText('Ctrl+Alt+Q')
  await settings.getByRole('button', { name: 'Close settings' }).click()
  await page.reload()
  await expect(page.locator('.app-statusbar kbd')).toHaveText('Ctrl+Alt+Q')
  await page.keyboard.press('Control+Alt+q')
  await expect(page.getByRole('dialog', { name: 'Quick Access', exact: true })).toBeVisible()
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('veyra:preferences') || '{}'))
  expect(stored.shortcuts.openQuick).toBe('Ctrl+Alt+Q')
})

test('Return requests confirmed browser filling for a connected login', async ({ page }) => {
  await installConnectedVault(page)
  await page.goto('/?window=quick')
  await page.getByRole('combobox', { name: 'Search vault' }).fill('Personal')
  await expect(page.getByRole('option')).toHaveCount(1)
  await page.keyboard.press('Enter')
  await expect.poll(() => page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.some(call => call.command === 'hide_quick_access'))).toBe(true)
  const requests = await page.evaluate(() => window.__VEYRA_UI_FIXTURE__.calls.filter(call => ['begin_browser_fill', 'open_website', 'copy_field'].includes(call.command)))
  expect(requests).toEqual([{ command: 'begin_browser_fill', args: { itemId: 'personal-login', expectedGeneration: 1 } }])
})
